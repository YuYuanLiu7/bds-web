-- ============================================================
-- orders 新增 fulfilled_at（履約完成時間戳）
-- 用途：讓「付款成功 → 開通權益」具備冪等性與當機補償能力。
--   - markOrderPaid 只保證「標記 paid」發生一次；
--   - 若在「已標記 paid」與「開通權益」之間發生程序中斷（部署/OOM/逾時），
--     PayUni 會重送通知，屆時可依 fulfilled_at 是否為 null 判斷「尚未開通」而自動補開通，
--     且不會重複開通（避免會員天數被重複累加）。
-- 冪等、可重複執行。
-- ============================================================

ALTER TABLE orders ADD COLUMN IF NOT EXISTS fulfilled_at timestamptz;
